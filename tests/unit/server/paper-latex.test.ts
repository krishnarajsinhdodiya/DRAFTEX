// D104: View LaTeX shows what the generator writes, for the paper's owner only.
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { type Actor, NotFoundError } from "@/lib/data";
import { paperLatex } from "@/server/paper-latex";
import { createTestDb, type TestDb } from "../../support/db";
import { paperMeta, templateFields, testSlot } from "../data/fixtures";

let t: TestDb;
let me: Actor;
let other: Actor;
let admin: Actor;
let paperId: string;

beforeAll(async () => {
  t = await createTestDb();
  const mk = async (email: string, role: "FACULTY" | "ADMIN") => {
    const u = await t.db.user.create({ data: { name: email, email, passwordHash: "x", role } });
    return { userId: u.id, role } as Actor;
  };
  me = await mk("owner@example.test", "FACULTY");
  other = await mk("other@example.test", "FACULTY");
  admin = await mk("admin@example.test", "ADMIN");
  const tpl = await t.data.templates.create(me, templateFields("View LaTeX"));
  paperId = (await t.data.papers.create(me, tpl.id, paperMeta())).id;
  await t.data.papers.saveSlot(
    me,
    paperId,
    testSlot({
      groupKey: "g2",
      position: 2,
      marks: 4,
      content: {
        type: "doc",
        content: [
          { type: "paragraph", content: [{ type: "text", text: "What does this print?" }] },
          { type: "codeBlock", attrs: { lines: ["print(1 + 1)"] } },
        ],
      },
      answerKey: {
        type: "doc",
        content: [{ type: "paragraph", content: [{ type: "text", text: "It prints 2." }] }],
      },
    }),
  );
});
afterAll(() => t.close());

describe("paperLatex", () => {
  it("returns the whole paper as the serializer writes it", async () => {
    const r = await paperLatex(t.data, me, paperId, "PAPER");
    expect(r.ok).toBe(true);
    if (!r.ok) return;
    expect(r.tex).toMatch(/^%% Generated by DRAFTEX/);
    expect(r.tex).toContain("\\usepackage{fancyvrb}");
    expect(r.tex).toContain("\nprint(1 + 1)\n\\end{Verbatim}\n");
  });

  it("returns one question, from its marker to its last line", async () => {
    const r = await paperLatex(t.data, me, paperId, "PAPER", "g2.2");
    expect(r).toEqual({
      ok: true,
      tex: expect.stringMatching(/^ {2}%% DX-SLOT g2\.2\n {2}\\question What does this print\?/),
    });
    if (r.ok) expect(r.tex).not.toContain("documentclass");
  });

  it("returns the key, and one question of it", async () => {
    const all = await paperLatex(t.data, me, paperId, "KEY");
    expect(all.ok && all.tex).toContain("It prints 2.");
    const one = await paperLatex(t.data, me, paperId, "KEY", "g2.2");
    expect(one.ok && one.tex).toMatch(/^%% DX-SLOT g2\.2\n/);
  });

  it("shows an empty question as the placeholder the preview prints", async () => {
    const r = await paperLatex(t.data, me, paperId, "PAPER", "g2.5");
    expect(r.ok && r.tex).toContain("(Question not written yet)");
  });

  it("says when a question is not on the paper, and refuses odd slot ids", async () => {
    for (const slot of ["g9.1", "g2.99", "../../x", "g2.2\n", ""]) {
      const r = await paperLatex(t.data, me, paperId, "PAPER", slot);
      expect(r).toMatchObject({ ok: false, status: 404 });
    }
  });

  it("is 'not found' to another teacher and to an administrator", async () => {
    for (const actor of [other, admin]) {
      await expect(paperLatex(t.data, actor, paperId, "PAPER")).rejects.toBeInstanceOf(
        NotFoundError,
      );
      await expect(paperLatex(t.data, actor, "guessed-id", "KEY")).rejects.toBeInstanceOf(
        NotFoundError,
      );
    }
  });

  it("names the questions that need fixing instead of returning broken LaTeX", async () => {
    await t.data.papers.saveSlot(
      me,
      paperId,
      testSlot({
        groupKey: "g2",
        position: 3,
        marks: 4,
        content: {
          type: "doc",
          content: [{ type: "codeBlock", attrs: { lines: ["\\end{Verbatim}"] } }],
        },
      }),
    );
    const r = await paperLatex(t.data, me, paperId, "PAPER");
    expect(r).toMatchObject({ ok: false, status: 422 });
    if (!r.ok) expect(r.problems[0]?.message).toMatch(/would end the code block/);
  });
});
